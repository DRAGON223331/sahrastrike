export const MAP = {
  minX: -40, maxX: 40, minZ: -30, maxZ: 30,
  boxes,
  sites: {
    A: { x: 18, z: -17, r: 5.5 },
    B: { x: 18, z: 17, r: 5.5 },
  },
  // نقاط قريبة من كل موقع للمهاجمين (يتم تصحيحها لأقرب نقطة سالكة)
  siteSpots: {
    A: [[17, -18], [19, -15], [15, -19], [18, -12], [14, -12]],
    B: [[17, 18], [19, 15], [15, 19], [18, 12], [14, 12]],
  },
  // نقاط تمركز للمدافعين
  holds: {
    A: [[22, -16], [16, -20], [18, -12], [24, -14]],
    B: [[22, 16], [16, 20], [18, 12], [24, 14]],
    M: [[15, -2], [15, 2], [12, 0]],
  },
  spawns: {
    atk: [[-35, -8], [-35, -4], [-35, 0], [-35, 4], [-35, 8]],
    def: [[35, -8], [35, -4], [35, 0], [35, 4], [35, 8]],
  },
  buyZoneX: 28, // أثناء الشراء المهاجم x <= -28 والمدافع x >= 28
};

export function siteAt(x, z) {
  for (const k of ['A', 'B']) {
    const s = MAP.sites[k];
    if (Math.hypot(x - s.x, z - s.z) <= s.r) return k;
  }
  return null;
}
