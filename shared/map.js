// خريطة "سوق الواحة" — مشتركة بين السيرفر والعميل
// الإحداثيات بالمتر. y لأعلى. اللاعب يبدأ من x سالب (المهاجمون) أو x موجب (المدافعون)

const boxes = [];
let nextId = 0;

function add(x, z, w, d, h, kind = 'building', extra = {}) {
  boxes.push({
    id: nextId++, x, z, w, d, h, kind,
    minX: x - w / 2, maxX: x + w / 2, minZ: z - d / 2, maxZ: z + d / 2,
    ...extra,
  });
}

// الأسوار الخارجية
add(0, -30.5, 82, 1, 6.5, 'outer');
