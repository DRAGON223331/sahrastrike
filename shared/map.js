add(-40.5, 0, 1, 62, 6.5, 'outer');
add(40.5, 0, 1, 62, 6.5, 'outer');

// جدار منطقة المهاجمين (x = -27) بثلاث فتحات: شمال / وسط / جنوب
for (const [z0, z1] of [[-30, -20], [-14, -5], [5, 14], [20, 30]]) {
  add(-27, (z0 + z1) / 2, 1.2, z1 - z0, 5, 'building');
}
// جدار منطقة المدافعين (x = 27)
for (const [z0, z1] of [[-30, -22], [-12, -4], [4, 12], [22, 30]]) {
  add(27, (z0 + z1) / 2, 1.2, z1 - z0, 5, 'building');
}

